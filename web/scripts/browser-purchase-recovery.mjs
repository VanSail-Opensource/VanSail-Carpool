import assert from 'node:assert/strict'

export async function purchaseRecoveryScenarios(scenario, size) {
  await scenario(size, 'renewal-expiry', 'purchase-recovery-audit.html?renewal&expires', async (page, capture) => {
    await page.getByRole('button', { name: 'Automatic renewal off', exact: true }).click()
    const dialog = page.getByRole('dialog')
    const net = dialog.locator('dl > div').filter({ hasText: 'Next-cycle price' }).locator('dd')
    await dialog.getByText('Price prepared', { exact: true }).waitFor()
    assert.equal(await net.innerText(), '8.00 TXB')
    await capture('prepared')
    await dialog.getByText('Price expired', { exact: true }).waitFor()
    assert.equal(await net.innerText(), 'Not available')
  })
  await scenario(size, 'renewal-deferred', 'purchase-recovery-audit.html?renewal&deferred-health', async page => {
    await page.getByRole('button', { name: 'Automatic renewal off', exact: true }).click()
    const dialog = page.getByRole('dialog')
    await dialog.getByText('Renewal is paused for service recovery', { exact: true }).waitFor()
    assert.equal(await dialog.getByText('Price prepared', { exact: true }).count(), 0)
    assert.equal(await dialog.locator('dl > div').filter({ hasText: 'Next-cycle price' }).locator('dd').innerText(), '8.00 TXB')
  })
  await scenario(size, 'renewal-reopened', 'purchase-recovery-audit.html?renewal&defer-pricing', async (page, capture) => {
    const open = page.getByRole('button', { name: 'Automatic renewal off', exact: true })
    await open.click()
    await page.waitForFunction(() => globalThis.__renewalPricingAudit.state.pricingReads === 1)
    await capture('loading')
    await page.getByRole('dialog').getByRole('button', { name: 'Close', exact: true }).click()
    await page.getByRole('dialog').waitFor({ state: 'hidden' })
    await open.click()
    await page.getByRole('dialog').getByText('Price prepared', { exact: true }).waitFor()
    await page.evaluate(() => globalThis.__renewalPricingAudit.release())
    await page.waitForFunction(() => globalThis.__renewalPricingAudit.state.pricingFinished === 2)
    assert.equal(await page.getByRole('dialog').getByText('Price prepared', { exact: true }).isVisible(), true)
    assert.equal(await page.evaluate(() => globalThis.__renewalPricingAudit.state.pricingReads), 2)
  })
  await scenario(size, 'renewal-error-retry', 'purchase-recovery-audit.html?renewal&pricing-error', async (page, capture) => {
    await page.getByRole('button', { name: 'Automatic renewal off', exact: true }).click()
    const dialog = page.getByRole('dialog')
    await dialog.getByText('The renewal price could not be refreshed. Please try again.', { exact: true }).waitFor()
    assert.equal(await dialog.locator('dl > div').filter({ hasText: 'Next-cycle price' }).locator('dd').innerText(), 'Not available')
    await capture('error')
    await page.evaluate(() => { globalThis.__renewalPricingAudit.state.error = false })
    await dialog.getByRole('button', { name: 'Try again', exact: true }).click()
    await dialog.getByText('Price prepared', { exact: true }).waitFor()
    assert.equal(await dialog.locator('dl > div').filter({ hasText: 'Next-cycle price' }).locator('dd').innerText(), '8.00 TXB')
    assert.equal(await page.evaluate(() => globalThis.__renewalPricingAudit.state.writes), 0)
  })
  await scenario(size, 'queued-target-replaced', 'purchase-recovery-audit.html', async page => {
    await page.getByRole('button', { name: 'Cancel queued ride', exact: true }).click()
    await page.getByRole('dialog').waitFor()
    await page.evaluate(() => globalThis.__purchaseRecoveryAudit.replace())
    await page.getByRole('dialog').waitFor({ state: 'hidden' })
    assert.deepEqual(await page.evaluate(() => globalThis.__purchaseRecoveryAudit.state.cancels), [])
    assert.equal(await page.getByRole('button', { name: 'Cancel queued ride', exact: true }).isEnabled(), true)
  })
  await scenario(size, 'queued-pending-replaced', 'purchase-recovery-audit.html?defer', async (page, capture) => {
    await page.getByRole('button', { name: 'Cancel queued ride', exact: true }).click()
    await page.getByRole('button', { name: 'Cancel and refund', exact: true }).click()
    await page.waitForFunction(() => globalThis.__purchaseRecoveryAudit.state.cancels.length === 1)
    await capture('cancelling')
    await page.evaluate(() => { globalThis.__purchaseRecoveryAudit.replace(); globalThis.__purchaseRecoveryAudit.release() })
    await page.getByRole('dialog').waitFor({ state: 'hidden' })
    await page.waitForFunction(() => globalThis.__purchaseRecoveryAudit.state.finished === 1)
    assert.deepEqual(await page.evaluate(() => globalThis.__purchaseRecoveryAudit.state.cancels), ['queued-1'])
    assert.equal(await page.evaluate(() => globalThis.__purchaseRecoveryAudit.state.changed), 0)
  })
  await scenario(size, 'queued-error-retry', 'purchase-recovery-audit.html?error', async (page, capture) => {
    await page.getByRole('button', { name: 'Cancel queued ride', exact: true }).click()
    const dialog = page.getByRole('dialog')
    const confirm = dialog.getByRole('button', { name: 'Cancel and refund', exact: true })
    await confirm.click()
    await dialog.getByRole('alert').getByText('Queued ride cancellation failed.', { exact: true }).waitFor()
    await capture('error')
    await page.evaluate(() => { globalThis.__purchaseRecoveryAudit.state.fail = false })
    await confirm.click()
    await dialog.waitFor({ state: 'hidden' })
    assert.deepEqual(await page.evaluate(() => globalThis.__purchaseRecoveryAudit.state.cancels), ['queued-1', 'queued-1'])
    assert.equal(await page.evaluate(() => globalThis.__purchaseRecoveryAudit.state.changed), 1)
  })
}
