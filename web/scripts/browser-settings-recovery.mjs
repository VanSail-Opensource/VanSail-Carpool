import assert from 'node:assert/strict'

export async function settingsRecoveryScenarios(scenario, size) {
  await scenario(size, 'admin-link-owner', 'browser-auth-audit.html?link&defer-link', async (page, capture) => {
    await page.waitForFunction(() => globalThis.__browserAuthAudit.links === 1)
    await page.evaluate(() => globalThis.__browserAuthAudit.replaceOwner())
    await page.waitForFunction(() => globalThis.__browserAuthAudit.links === 2)
    await page.evaluate(() => globalThis.__browserAuthAudit.releaseLink())
    assert.equal(await page.getByRole('textbox', { name: 'Copy access link', exact: true }).count(), 0)
    await capture('retired')
    await page.evaluate(() => globalThis.__browserAuthAudit.releaseLink())
    const input = page.getByRole('textbox', { name: 'Copy access link', exact: true })
    await input.waitFor()
    assert.match(await input.inputValue(), /token=audit-link-2$/)
    await page.getByRole('button', { name: 'Generate new link', exact: true }).click()
    await page.waitForFunction(() => globalThis.__browserAuthAudit.links === 3)
    await page.evaluate(() => { globalThis.__browserAuthAudit.logoutMember(); globalThis.__browserAuthAudit.releaseLink() })
    await input.waitFor({ state: 'hidden' })
    assert.equal(await page.getByRole('button', { name: 'Open admin console', exact: true }).isEnabled(), false)
  })
  await scenario(size, 'admin-link-expiry-error', 'browser-auth-audit.html?link&link-refresh-error', async (page, capture) => {
    const input = page.getByRole('textbox', { name: 'Copy access link', exact: true })
    await input.waitFor()
    await page.evaluate(() => globalThis.__browserAuthAudit.expireLink())
    await page.getByRole('button', { name: 'Copy access link', exact: true }).click()
    await page.getByText('Could not create an access link. Please retry.', { exact: true }).waitFor()
    assert.equal(await input.count(), 0)
    assert.equal(await page.evaluate(() => globalThis.__browserAuthAudit.copied), '')
    await capture('error')
    await page.evaluate(() => { globalThis.__browserAuthAudit.recoverLink = true })
    await page.getByRole('button', { name: 'Generate new link', exact: true }).click()
    await input.waitFor()
    await page.getByRole('button', { name: 'Copy access link', exact: true }).click()
    await page.waitForFunction(() => globalThis.__browserAuthAudit.copied.endsWith('token=audit-link-3'))
  })
  await scenario(size, 'settings-activation-owner', 'settings-audit.html', async (page, capture) => {
    await page.getByRole('button', { name: 'Activate', exact: true }).click()
    const dialog = page.getByRole('dialog')
    const confirmation = page.getByRole('textbox', { name: 'Type ACTIVATE NEXT COMBO to confirm', exact: true })
    await confirmation.fill('ACTIVATE NEXT COMBO')
    await capture('reviewed')
    await page.evaluate(() => globalThis.__controlsAudit.replaceOwner())
    await dialog.waitFor({ state: 'hidden' })
    assert.equal(await page.evaluate(() => globalThis.__controlsAudit.activations), 0)
    await page.getByRole('button', { name: 'Activate', exact: true }).click()
    assert.equal(await confirmation.inputValue(), '')
    await confirmation.fill('ACTIVATE NEXT COMBO')
    await dialog.getByRole('button', { name: 'Activate', exact: true }).click()
    await page.waitForFunction(() => globalThis.__controlsAudit.activations === 1)
    assert.deepEqual(await page.evaluate(() => globalThis.__controlsAudit.activationTargets), [{ current: 'replacement-current', queued: 'replacement-queued' }])
  })
  await scenario(size, 'settings-tag-retry', 'settings-audit.html?save-error&noqueued', async (page, capture) => {
    const tag = page.getByRole('textbox', { name: 'Group member tag', exact: true })
    await tag.fill('Reviewed tag')
    const save = page.getByRole('button', { name: 'Save', exact: true })
    await save.click()
    await page.getByText('Telegram could not confirm your tag. Use at most 16 characters without emoji, then retry.', { exact: true }).waitFor()
    assert.equal(await tag.inputValue(), 'Reviewed tag')
    await capture('error')
    await page.evaluate(() => { globalThis.__controlsAudit.recover = true })
    await save.click()
    await page.waitForFunction(() => globalThis.__controlsAudit.tagWrites.length === 2)
    assert.equal(await save.isEnabled(), false)
    assert.equal(await tag.inputValue(), 'Reviewed tag')
  })
}
