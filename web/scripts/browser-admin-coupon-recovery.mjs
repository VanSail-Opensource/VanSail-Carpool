import assert from 'node:assert/strict'

export async function adminCouponRecoveryScenarios(scenario, size) {
  await scenario(size, 'admin-coupon-save-recovery', 'coupon-recovery-audit.html?defer&refresh-error&slow', async (page, capture) => {
    await page.getByRole('status').filter({ hasText: 'Loading' }).waitFor()
    await capture('loading')
    await page.getByRole('button', { name: 'Edit RETAINED', exact: true }).click()
    const dialog = page.getByRole('dialog')
    const name = dialog.getByLabel('Name', { exact: true })
    await name.fill('Confirmed coupon')
    await dialog.getByRole('button', { name: 'Save coupon', exact: true }).click()
    await page.waitForFunction(() => globalThis.__couponRecoveryAudit.pending === 1)
    assert.equal(await name.isEditable(), false)
    assert.equal(await dialog.getByRole('button', { name: 'Cancel', exact: true }).isEnabled(), false)
    await page.keyboard.press('Escape')
    assert.equal(await dialog.isVisible(), true)
    await capture('pending')
    await page.evaluate(() => globalThis.__couponRecoveryAudit.release(true))
    await dialog.getByText('The coupon could not be saved.', { exact: true }).waitFor()
    await capture('refusal')
    await dialog.getByRole('button', { name: 'Save coupon', exact: true }).click()
    await page.waitForFunction(() => globalThis.__couponRecoveryAudit.pending === 1)
    await page.evaluate(() => globalThis.__couponRecoveryAudit.release())
    await dialog.waitFor({ state: 'hidden' })
    await page.getByRole('alert').filter({ hasText: 'Coupons could not be loaded.' }).waitFor()
    await page.getByText('Confirmed coupon', { exact: true }).waitFor()
    assert.deepEqual(await page.evaluate(() => globalThis.__couponRecoveryAudit.writes), [
      { id: 'coupon-audit', body: { name: 'Confirmed coupon' } },
      { id: 'coupon-audit', body: { name: 'Confirmed coupon' } },
    ])
    await capture('confirmed-with-read-error')
    await page.evaluate(() => { globalThis.__couponRecoveryAudit.recover = true })
    await page.getByRole('button', { name: 'Refresh', exact: true }).click()
    await page.getByRole('alert').waitFor({ state: 'hidden' })
  })
  await scenario(size, 'admin-coupon-deactivate-recovery', 'coupon-recovery-audit.html?defer&refresh-error', async (page, capture) => {
    await page.getByRole('button', { name: 'Deactivate', exact: true }).click()
    const dialog = page.getByRole('dialog')
    await dialog.getByRole('button', { name: 'Deactivate', exact: true }).click()
    await page.waitForFunction(() => globalThis.__couponRecoveryAudit.pending === 1)
    assert.equal(await dialog.getByRole('button', { name: 'Cancel', exact: true }).isEnabled(), false)
    await page.keyboard.press('Escape')
    assert.equal(await dialog.isVisible(), true)
    await capture('pending')
    await page.evaluate(() => globalThis.__couponRecoveryAudit.release())
    await dialog.waitFor({ state: 'hidden' })
    await page.getByRole('alert').filter({ hasText: 'Coupons could not be loaded.' }).waitFor()
    await page.getByText('Paused', { exact: true }).waitFor()
    assert.equal(await page.getByRole('button', { name: 'Deactivate', exact: true }).count(), 0)
    await capture('inactive-with-read-error')
    await page.evaluate(() => { globalThis.__couponRecoveryAudit.recover = true })
    await page.getByRole('button', { name: 'Refresh', exact: true }).click()
    await page.getByRole('alert').waitFor({ state: 'hidden' })
    assert.deepEqual(await page.evaluate(() => globalThis.__couponRecoveryAudit.deactivations), ['coupon-audit'])
  })
  await scenario(size, 'admin-coupon-options-retry', 'coupon-recovery-audit.html?options-error', async (page, capture) => {
    await page.getByRole('button', { name: 'Edit RETAINED', exact: true }).click()
    const dialog = page.getByRole('dialog')
    const error = dialog.getByText('Eligible plans and squads could not be refreshed. Existing selections were kept.', { exact: true })
    await error.waitFor()
    await capture('options-error')
    await page.evaluate(() => { globalThis.__couponRecoveryAudit.optionsRecovered = true })
    await dialog.getByRole('button', { name: 'Try again', exact: true }).click()
    await error.waitFor({ state: 'hidden' })
    assert.equal(await dialog.getByLabel('Name', { exact: true }).inputValue(), 'Reviewed coupon')
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
    await dialog.waitFor({ state: 'hidden' })
    assert.equal(await page.evaluate(() => globalThis.__couponRecoveryAudit.writes.length), 0)
  })
  await scenario(size, 'admin-coupon-retired-write', 'coupon-recovery-audit.html?defer', async (page, capture) => {
    await page.getByRole('button', { name: 'Edit RETAINED', exact: true }).click()
    const dialog = page.getByRole('dialog')
    await dialog.getByLabel('Name', { exact: true }).fill('Retired coupon')
    await dialog.getByRole('button', { name: 'Save coupon', exact: true }).click()
    await page.waitForFunction(() => globalThis.__couponRecoveryAudit.pending === 1)
    await capture('pending')
    await page.evaluate(() => globalThis.__couponRecoveryAudit.retire())
    await page.locator('[data-test="retired-coupon-workspace"]').waitFor()
    await page.evaluate(() => globalThis.__couponRecoveryAudit.release())
    assert.equal(await page.evaluate(() => globalThis.__couponRecoveryAudit.reads), 1)
    assert.equal(await page.getByText('Retired coupon', { exact: true }).count(), 0)
  })
}
