import assert from 'node:assert/strict'

export async function adminSettingsRecoveryScenarios(scenario, size) {
  for (const outcome of ['success', 'failure']) {
    await scenario(size, 'admin-settings-retired-read-' + outcome, 'emby-connection-audit.html?cached-refresh', async (page, capture) => {
      await page.waitForFunction(() => globalThis.__embyConnectionAudit.pendingReads === 3)
      await page.getByRole('tab', { name: 'Payment profiles', exact: true }).click()
      await page.locator('#billing-minimum-txb').fill('2.00')
      await page.getByRole('button', { name: 'Details', exact: true }).click()
      const dialog = page.getByRole('dialog')
      await dialog.getByRole('textbox', { name: 'Provider name', exact: true }).fill('Reviewed provider')
      await dialog.getByRole('button', { name: 'Close', exact: true }).last().click()
      await dialog.waitFor({ state: 'hidden' })
      await page.getByRole('tab', { name: 'Activity', exact: true }).click()
      await page.locator('#daily-reward-minimum').fill('3.00')
      await page.locator('#daily-reward-maximum').fill('4.00')
      await capture('reviewed')
      await page.getByRole('button', { name: 'Save settings', exact: true }).click()
      await page.getByText('Settings saved', { exact: true }).waitFor()
      await page.evaluate(fail => globalThis.__embyConnectionAudit.releaseReads(fail), outcome === 'failure')
      assert.equal(await page.locator('#daily-reward-minimum').inputValue(), '3.00')
      assert.equal(await page.locator('#daily-reward-maximum').inputValue(), '4.00')
      await page.getByRole('tab', { name: 'Payment profiles', exact: true }).click()
      assert.equal(await page.locator('#billing-minimum-txb').inputValue(), '2.00')
      assert.equal(await page.locator('#billing-maximum-txb').inputValue(), '100.00')
      assert.equal(await page.getByText('Reviewed provider', { exact: true }).count(), 1)
      assert.equal(await page.getByText('Admin data could not be loaded.', { exact: true }).count(), 0)
      const state = await page.evaluate(() => globalThis.__embyConnectionAudit)
      assert.deepEqual(state.amountWrites, [{ minimum: '200', maximum: '10000' }])
      assert.equal(state.profileWrites.length, 1)
      assert.equal(state.profileWrites[0].providerName, 'Reviewed provider')
      assert.equal(state.activityWrites.length, 1)
      assert.equal(state.activityWrites[0].dailyRewardMinTxb, '3.00')
      assert.equal(state.activityWrites[0].dailyRewardMaxTxb, '4.00')
    })
  }
  await scenario(size, 'admin-profile-delete-retired-read', 'emby-connection-audit.html?cached-refresh', async (page, capture) => {
    await page.waitForFunction(() => globalThis.__embyConnectionAudit.pendingReads === 3)
    await page.getByRole('tab', { name: 'Payment profiles', exact: true }).click()
    await page.getByRole('button', { name: 'Delete payment profile', exact: true }).click()
    const dialog = page.getByRole('dialog')
    await capture('review')
    await dialog.getByRole('button', { name: 'Delete profile', exact: true }).click()
    await dialog.waitFor({ state: 'hidden' })
    await page.getByText('Payment profile deleted.', { exact: true }).waitFor()
    await page.evaluate(() => globalThis.__embyConnectionAudit.releaseReads())
    assert.equal(await page.getByText('Constructed provider', { exact: true }).count(), 0)
    assert.equal(await page.getByRole('button', { name: 'Delete payment profile', exact: true }).count(), 0)
    assert.deepEqual(await page.evaluate(() => globalThis.__embyConnectionAudit.profileDeletes), ['constructed-profile'])
  })
}
