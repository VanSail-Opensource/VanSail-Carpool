import assert from 'node:assert/strict'

export async function pmRecoveryScenarios(scenario, size) {
  await scenario(size, 'pm-moderation-recovery', 'pm-admin-audit.html?recovery&lost&pending', async (page, capture) => {
    const blocked = page.locator('#user-pm-block-ada')
    await blocked.waitFor()
    assert.equal(await blocked.getAttribute('aria-checked'), 'false')
    await blocked.click()
    await page.locator('.operation-status .notice--warning').waitFor()
    const lost = await page.evaluate(() => globalThis.__pmAudit)
    assert.equal(lost.keys.length, 1)
    assert.equal(lost.changes, 1)
    assert.equal(lost.reads, 1, 'failed moderation triggered a parent reload')
    await capture('lost-response')
    await page.evaluate(() => { globalThis.__pmAudit.recover = true; globalThis.__pmAudit.failure = true })
    await blocked.click()
    await page.locator('[data-test="pm-profile-error"]').waitFor()
    await page.waitForFunction(() => globalThis.__pmAudit.polls > 0)
    assert.equal(await blocked.isDisabled(), true, 'parent refresh discarded the active receipt')
    assert.equal(await page.locator('.operation-status .notice--info').count(), 1)
    const replay = await page.evaluate(() => globalThis.__pmAudit)
    assert.equal(replay.keys.length, 2)
    assert.equal(replay.keys[1], replay.keys[0])
    assert.equal(replay.changes, 1, 'retry duplicated the accepted moderation')
    await capture('retained-read-error')
    await page.evaluate(() => { globalThis.__pmAudit.failure = false })
    await page.locator('[data-test="pm-profile-retry"]').click()
    await page.locator('[data-test="pm-profile-error"]').waitFor({ state: 'hidden' })
    await page.waitForFunction(() => globalThis.document.querySelector('#user-pm-block-ada')?.getAttribute('aria-checked') === 'true')
    assert.equal(await blocked.isDisabled(), true)
    await capture('accepted-flags')
    await page.evaluate(() => { globalThis.__pmAudit.pending = false })
    await page.locator('.operation-status .notice--success').waitFor()
    assert.equal(await blocked.isEnabled(), true)
    assert.equal(await page.evaluate(() => globalThis.__pmAudit.changes), 1)
  })
}
