import assert from 'node:assert/strict'

const metricWarning = 'Live status is unavailable. Configuration and recovery actions remain available; any previous observations are not current.'
export async function xnodeAvailabilityScenarios(scenario, size) {
  await scenario(size, 'xnode-metrics-failure', 'xnode-audit.html?availability&unavailable=metrics&long-names', async (page, capture) => {
    await page.getByRole('status').filter({ hasText: metricWarning }).waitFor()
    await page.locator('.xnode-row').first().waitFor()
    assert.equal(await page.getByText('Status unavailable', { exact: true }).count(), 2)
    assert.equal(await page.getByRole('button', { name: 'Add node', exact: true }).isEnabled(), true)
    assert.deepEqual(await page.evaluate(() => globalThis.__xnodeAvailability.calls.slice().sort()), ['configurations', 'endpoints', 'metrics', 'nodes'])
    await capture('available-without-telemetry')
    await page.locator('.xnode-row').first().getByRole('button', { name: 'Edit', exact: true }).click()
    const dialog = page.getByRole('dialog')
    await dialog.getByLabel('Name', { exact: true }).fill('Reviewed node')
    await page.evaluate(() => {
      globalThis.__falseLoadError = false
      globalThis.__closeObserver = new globalThis.MutationObserver(() => {
        if (globalThis.document.querySelector('[role="dialog"]')?.textContent?.includes('Could not load node data. Please retry.')) globalThis.__falseLoadError = true
      })
      globalThis.__closeObserver.observe(globalThis.document.body, { childList: true, subtree: true, characterData: true })
    })
    await dialog.getByRole('button', { name: 'Save', exact: true }).click()
    await dialog.waitFor({ state: 'hidden' })
    assert.equal(await page.evaluate(() => { globalThis.__closeObserver.disconnect(); return globalThis.__falseLoadError }), false)
    const writes = await page.evaluate(() => globalThis.__xnodeAudit.writes)
    assert.equal(writes.length, 1)
    assert.equal(writes[0].node.name, 'Reviewed node')
    assert.equal(await page.getByText('Reviewed node', { exact: true }).isVisible(), true)
    assert.deepEqual(Object.keys(writes[0].node).sort(), ['configId', 'countryCode', 'enabled', 'id', 'name', 'providerName'])
  })
  await scenario(size, 'xnode-tab-isolation', 'xnode-audit.html?availability&unavailable=groups&xnodeTab=groups', async (page, capture) => {
    await page.locator('.error-state').waitFor()
    assert.equal(await page.locator('.xnode-row').count(), 0)
    await capture('required-inventory-error')
    await page.getByRole('tab', { name: 'Global settings', exact: true }).click()
    await page.getByLabel('Global connections per user', { exact: true }).waitFor()
    assert.equal(new globalThis.URL(page.url()).searchParams.get('xnodeTab'), 'global')
    assert.equal(await page.locator('.error-state').count(), 0)
    assert.equal(await page.evaluate(() => globalThis.__xnodeAvailability.calls.includes('metrics')), false)
    await page.reload()
    await page.getByLabel('Global connections per user', { exact: true }).waitFor()
    assert.deepEqual(await page.evaluate(() => globalThis.__xnodeAvailability.calls), ['global'])
    await capture('independent-global-settings')
  })
  await scenario(size, 'xnode-stale-status', 'xnode-audit.html?availability&fail-after-first=metrics', async (page, capture) => {
    await page.getByText('Online', { exact: true }).waitFor()
    await page.getByRole('status').filter({ hasText: metricWarning }).waitFor()
    assert.equal(await page.getByText('Not current', { exact: true }).count(), 2)
    assert.equal(await page.getByText('Online', { exact: true }).count(), 0)
    assert.equal(await page.getByRole('button', { name: 'Add node', exact: true }).isEnabled(), true)
    await capture('cached-status-marked-stale')
  })
  await scenario(size, 'xnode-loading-empty', 'xnode-audit.html?availability&empty&slow-read=nodes&delay=1600', async (page, capture) => {
    await page.locator('.admin-loading').waitFor()
    await capture('loading')
    await page.getByText('No nodes configured.', { exact: true }).waitFor()
    assert.equal(await page.getByRole('button', { name: 'Add node', exact: true }).isEnabled(), false)
    await capture('empty')
  })
  await scenario(size, 'xnode-ddns-discovery-unavailable', 'xnode-audit.html?ddns&zones-empty', async (page, capture) => {
    await page.locator('.xnode-row').first().getByRole('button', { name: 'Edit', exact: true }).click()
    const dialog = page.getByRole('dialog')
    await dialog.locator('summary').filter({ hasText: 'DDNS' }).click()
    const zone = dialog.getByLabel('DNS zone', { exact: true })
    await zone.fill('example.com')
    await dialog.getByLabel('Record name', { exact: true }).fill('node.example.com')
    const ttl = dialog.getByLabel('TTL (seconds)', { exact: true })
    await ttl.fill('2147483648')
    const ttlError = dialog.getByText('Enter a whole TTL from 0 to 2147483647 seconds. 0 uses the default.', { exact: true })
    await ttlError.waitFor()
    assert.equal(await dialog.getByRole('button', { name: 'Save', exact: true }).isEnabled(), false)
    await ttlError.scrollIntoViewIfNeeded()
    await capture('invalid-ttl-with-manual-zone')
    await ttl.fill('300')
    await dialog.getByRole('button', { name: 'Save', exact: true }).click()
    await dialog.waitFor({ state: 'hidden' })
    const writes = await page.evaluate(() => globalThis.__xnodeAudit.writes)
    assert.equal(writes[0].settings.ddns[0].name, 'node.example.com')
    assert.equal(writes[0].settings.ddns[0].zone, 'example.com')
  })
}
