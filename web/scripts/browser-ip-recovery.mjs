import assert from 'node:assert/strict'

export async function ipRecoveryScenarios(scenario, size) {
  await scenario(size, 'ip-admin-required-read', 'ip-lookup-audit.html?admin&admin-load-error', async (page, capture) => {
    await page.getByRole('button', { name: 'Try again', exact: true }).waitFor()
    assert.equal(await page.getByRole('button', { name: 'Save', exact: true }).isEnabled(), false)
    const fields = page.locator('.lookup-settings__fields')
    assert.equal(await fields.evaluate(element => element.tagName === 'FIELDSET' && element.disabled), true)
    const controls = fields.locator('input, button, select, textarea')
    assert.ok(await controls.count() > 0)
    for (const control of await controls.all()) assert.equal(await control.isDisabled(), true)
    assert.equal(await page.evaluate(() => globalThis.__ipAudit.counters().savedBody), null)
    await capture('unavailable-read-only')
    await page.evaluate(() => { globalThis.__ipAudit.admin.recovered = true })
    await page.getByRole('button', { name: 'Try again', exact: true }).click()
    await page.getByRole('button', { name: 'Try again', exact: true }).waitFor({ state: 'hidden' })
    assert.equal(await page.getByRole('button', { name: 'Save', exact: true }).isEnabled(), true)
    assert.equal(await page.evaluate(() => globalThis.__ipAudit.admin.settingsReads), 2)
    await page.getByRole('button', { name: 'Save', exact: true }).click()
    await page.waitForFunction(() => globalThis.__ipAudit.counters().savedBody !== null)
    await capture('recovered-save')
  })
  await scenario(size, 'ip-partial-topology', 'ip-recovery-audit.html', async (page, capture) => {
    const transit = page.locator('[data-asn="64501"]')
    await transit.waitFor()
    assert.equal(await page.locator('[data-asn="64999"]').count(), 0)
    await transit.press('Enter')
    const routes = page.locator('.graph-focus-routes button')
    assert.equal(await routes.count(), 25)
    await page.getByRole('button', { name: 'Next routes', exact: true }).click()
    assert.equal(await routes.count(), 5)
    await routes.first().click()
    await capture('selected')
    await page.evaluate(() => globalThis.__ipRecoveryAudit.shrink())
    await page.waitForFunction(() => globalThis.document.querySelectorAll('.graph-focus-routes button').length === 1)
    assert.equal(await routes.first().getAttribute('aria-pressed'), 'false')
    assert.equal(await page.getByRole('button', { name: 'Next routes', exact: true }).count(), 0)
    await capture('contracted')
    await page.evaluate(() => globalThis.__ipRecoveryAudit.removeTransit())
    await page.locator('.graph-focus').waitFor({ state: 'hidden' })
    assert.equal(await page.locator('[data-asn="64500"]').count(), 1)
    assert.equal(await page.locator('[data-asn="64501"]').count(), 0)
    const bounds = await page.locator('.graph-viewport').boundingBox()
    assert.ok(bounds && bounds.x >= 0 && bounds.x + bounds.width <= size.viewport.width)
  })
  await scenario(size, 'ip-live-owner', 'ip-recovery-audit.html?live', async (page, capture) => {
    await page.getByText('previous-owner.example', { exact: true }).waitFor()
    assert.equal(await page.evaluate(() => globalThis.__ipRecoveryAudit.reads()), 0)
    await page.evaluate(() => globalThis.__ipRecoveryAudit.replaceOwner())
    await page.waitForFunction(() => globalThis.__ipRecoveryAudit.reads() === 1)
    assert.equal(await page.getByText('previous-owner.example', { exact: true }).count(), 0)
    await capture('loading')
    await page.evaluate(() => { globalThis.__ipRecoveryAudit.logout(); globalThis.__ipRecoveryAudit.release() })
    assert.equal(await page.getByText('retired-read.example', { exact: true }).count(), 0)
    assert.equal(await page.getByText('previous-owner.example', { exact: true }).count(), 0)
    assert.equal(await page.evaluate(() => globalThis.__ipRecoveryAudit.reads()), 1)
  })
}
