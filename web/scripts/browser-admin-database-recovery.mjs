import assert from 'node:assert/strict'

async function openDraft(page, label = 'Reviewed change') {
  await page.getByRole('button', { name: 'Edit row', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('label', { exact: true }).fill(label)
  await dialog.getByLabel('Reason', { exact: true }).fill('Repair the operational label')
  return dialog
}
async function confirmReview(dialog) {
  await dialog.getByLabel('Type EDIT operational_records', { exact: true }).fill('EDIT operational_records')
  await dialog.getByRole('button', { name: 'Apply reviewed change', exact: true }).click()
}

export async function adminDatabaseRecoveryScenarios(scenario, size) {
  await scenario(size, 'admin-database-review-apply-recovery', 'database-audit.html?slow&defer-review&defer-apply', async (page, capture) => {
    await capture('loading')
    const dialog = await openDraft(page)
    assert.equal(await dialog.getByLabel('amount', { exact: true }).inputValue(), '900719925474099312345')
    await dialog.getByRole('button', { name: 'Review change', exact: true }).click()
    await page.waitForFunction(() => globalThis.databaseAudit.pendingReview === 1)
    assert.equal(await dialog.getByLabel('label', { exact: true }).isEditable(), false)
    assert.equal(await dialog.getByRole('button', { name: 'Close record editor', exact: true }).isEnabled(), false)
    await page.keyboard.press('Escape')
    assert.equal(await dialog.isVisible(), true)
    await capture('review-pending')
    await page.evaluate(() => globalThis.databaseAudit.release())
    await dialog.getByRole('region', { name: 'Review exact changes', exact: true }).waitFor()
    await confirmReview(dialog)
    await page.waitForFunction(() => globalThis.databaseAudit.pendingApply === 1)
    assert.equal(await dialog.getByLabel('Type EDIT operational_records', { exact: true }).isEditable(), false)
    await capture('apply-pending')
    await page.evaluate(() => globalThis.databaseAudit.release(true))
    await dialog.getByText('The change could not be confirmed. Refresh the record before retrying.', { exact: true }).waitFor()
    await capture('apply-error')
    await dialog.getByRole('button', { name: 'Apply reviewed change', exact: true }).click()
    await page.waitForFunction(() => globalThis.databaseAudit.pendingApply === 1)
    await page.evaluate(() => globalThis.databaseAudit.release())
    await dialog.waitFor({ state: 'hidden' })
    await page.getByText('Reviewed change applied', { exact: true }).waitFor()
    await page.getByText('Reviewed change', { exact: true }).waitFor()
    const state = await page.evaluate(() => globalThis.databaseAudit)
    assert.equal(state.reviews.length, 1)
    assert.equal(state.applies.length, 2)
    assert.deepEqual(state.applies[0], state.applies[1])
    assert.equal(state.applies[0].values.amount, '900719925474099312345')
  })
  await scenario(size, 'admin-database-retired-metadata', 'database-audit.html?cached-metadata', async (page, capture) => {
    await page.waitForFunction(() => globalThis.databaseAudit.pendingMetadata === 1)
    const dialog = await openDraft(page)
    await dialog.getByRole('button', { name: 'Review change', exact: true }).click()
    await dialog.getByRole('region', { name: 'Review exact changes', exact: true }).waitFor()
    await page.evaluate(() => globalThis.databaseAudit.releaseMetadata())
    assert.equal(await dialog.getByRole('heading', { name: 'Edit operational_records row', exact: true }).isVisible(), true)
    assert.equal(await page.evaluate(() => globalThis.databaseAudit.rowReads), 0)
    await capture('obsolete-metadata-retired')
    await confirmReview(dialog)
    await dialog.waitFor({ state: 'hidden' })
    await page.getByText('Reviewed change', { exact: true }).waitFor()
    assert.equal(await page.evaluate(() => globalThis.databaseAudit.applies[0].table), 'operational_records')
  })
  await scenario(size, 'admin-database-nullable-boolean', 'database-audit.html', async (page, capture) => {
    const dialog = await openDraft(page)
    await dialog.getByRole('checkbox', { name: 'Store NULL', exact: true }).uncheck()
    assert.equal(await dialog.getByRole('switch', { name: 'enabled', exact: true }).isChecked(), false)
    await dialog.getByRole('button', { name: 'Review change', exact: true }).click()
    await dialog.getByRole('region', { name: 'Review exact changes', exact: true }).waitFor()
    assert.equal(await page.evaluate(() => globalThis.databaseAudit.reviews[0].values.enabled), false)
    assert.equal(await page.evaluate(() => globalThis.databaseAudit.applies.length), 0)
    await capture('false-reviewed')
  })
  await scenario(size, 'admin-database-retired-apply', 'database-audit.html?defer-apply', async (page, capture) => {
    const dialog = await openDraft(page)
    await dialog.getByRole('button', { name: 'Review change', exact: true }).click()
    await confirmReview(dialog)
    await page.waitForFunction(() => globalThis.databaseAudit.pendingApply === 1)
    await capture('pending')
    await page.evaluate(() => globalThis.databaseAudit.retire())
    await page.locator('[data-test="retired-database-workspace"]').waitFor()
    await page.evaluate(() => globalThis.databaseAudit.release())
    assert.equal(await page.evaluate(() => globalThis.databaseAudit.applies.length), 1)
    assert.equal(await page.evaluate(() => globalThis.databaseAudit.rowReads), 1)
    assert.equal(await page.getByText('Reviewed change applied', { exact: true }).count(), 0)
  })
}
