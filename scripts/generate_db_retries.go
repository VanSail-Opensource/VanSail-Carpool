//go:build ignore

// Generates complete-operation retries only for Store methods with one SQL
// transaction and no SQL calls outside it. Network work has no place in Store.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

func main() {
	paths, err := filepath.Glob("internal/platform/database/*.go")
	check(err)
	for _, path := range paths {
		if strings.HasSuffix(path, "_test.go") || strings.HasSuffix(path, "_retry_generated.go") {
			continue
		}
		raw, err := os.ReadFile(path)
		check(err)
		fs := token.NewFileSet()
		file, err := parser.ParseFile(fs, path, raw, parser.ParseComments)
		check(err)
		imports := map[string]string{}
		for _, imp := range file.Imports {
			value, err := strconv.Unquote(imp.Path.Value)
			check(err)
			name := filepath.Base(value)
			if imp.Name != nil {
				name = imp.Name.Name
			}
			imports[name] = value
		}
		var wrappers []string
		used := map[string]bool{}
		type edit struct {
			start, end int
			value      string
		}
		var edits []edit
		for _, decl := range file.Decls {
			fn, ok := decl.(*ast.FuncDecl)
			if !ok || fn.Recv == nil || fn.Body == nil || fn.Type.Results == nil {
				continue
			}
			body := string(raw[fs.Position(fn.Body.Pos()).Offset:fs.Position(fn.Body.End()).Offset])
			if strings.Count(body, "s.db.BeginTx(") != 1 || strings.Count(body, "s.db.") != 1 {
				continue
			}
			if strings.Contains(body, "s.groupFacts") || strings.Contains(body, "s.firewallSweepCursor") || strings.Contains(body, "s.diyCleanupCursor") {
				continue
			}
			last := fn.Type.Results.List[len(fn.Type.Results.List)-1]
			if typ, ok := last.Type.(*ast.Ident); !ok || typ.Name != "error" {
				continue
			}
			var params []string
			for _, field := range fn.Type.Params.List {
				for _, name := range field.Names {
					params = append(params, name.Name)
				}
			}
			if len(params) == 0 || params[0] != "ctx" {
				continue
			}
			if _, ok := fn.Type.Params.List[len(fn.Type.Params.List)-1].Type.(*ast.Ellipsis); ok {
				params[len(params)-1] += "..."
			}
			var returns []string
			for _, field := range fn.Type.Results.List {
				for j := 0; j < max(1, len(field.Names)); j++ {
					returns = append(returns, fmt.Sprintf("r%d", len(returns)))
				}
			}
			errorName := returns[len(returns)-1]
			ast.Inspect(fn.Type, func(node ast.Node) bool {
				if selector, ok := node.(*ast.SelectorExpr); ok {
					if id, ok := selector.X.(*ast.Ident); ok {
						used[id.Name] = true
					}
				}
				return true
			})
			name := strings.TrimPrefix(fn.Name.Name, "retryAttempt_")
			attemptName := "retryAttempt_" + name
			start, end := fs.Position(fn.Pos()).Offset, fs.Position(fn.Body.Pos()).Offset
			signature := string(raw[start:end])
			signature = strings.Replace(signature, fn.Name.Name+"(", name+"(", 1)
			wrappers = append(wrappers, fmt.Sprintf("%s{\n for retryIndex:=0;;retryIndex++ {\n %s := s.%s(%s)\n if !s.retryTransaction(ctx,%s,retryIndex) { return %s }\n }\n}\n", signature, strings.Join(returns, ","), attemptName, strings.Join(params, ","), errorName, strings.Join(returns, ",")))
			if fn.Name.Name != attemptName {
				edits = append(edits, edit{fs.Position(fn.Name.Pos()).Offset, fs.Position(fn.Name.End()).Offset, attemptName})
			}
			lock := "s.writeMu.Lock()\n\tdefer s.writeMu.Unlock()"
			if i := strings.Index(body, lock); i >= 0 {
				position := fs.Position(fn.Body.Pos()).Offset + i
				edits = append(edits, edit{position, position + len(lock), "if !IsPostgres(s.db) { s.writeMu.Lock(); defer s.writeMu.Unlock() }"})
			}
		}
		if len(wrappers) == 0 {
			continue
		}
		var generated bytes.Buffer
		generated.WriteString("// Code generated by scripts/generate_db_retries.go; DO NOT EDIT.\npackage database\nimport (\n")
		var names []string
		for name := range used {
			if _, ok := imports[name]; ok {
				names = append(names, name)
			}
		}
		sort.Strings(names)
		for _, name := range names {
			fmt.Fprintf(&generated, "%s %q\n", name, imports[name])
		}
		generated.WriteString(")\n" + strings.Join(wrappers, "\n"))
		formatted, err := format.Source(generated.Bytes())
		check(err)
		check(os.WriteFile(strings.TrimSuffix(path, ".go")+"_retry_generated.go", formatted, 0o644))
		sort.Slice(edits, func(i, j int) bool { return edits[i].start > edits[j].start })
		for _, e := range edits {
			raw = append(append(append([]byte{}, raw[:e.start]...), []byte(e.value)...), raw[e.end:]...)
		}
		formatted, err = format.Source(raw)
		check(err)
		check(os.WriteFile(path, formatted, 0o644))
	}
	documentWrappers()
}

func documentWrappers() {
	path := "internal/platform/database/README.md"
	raw, err := os.ReadFile(path)
	check(err)
	const marker = "\n<!-- generated transaction retry map -->"
	text := strings.SplitN(string(raw), marker, 2)[0]
	files, err := filepath.Glob("internal/platform/database/*_retry_generated.go")
	check(err)
	text += marker + "\n\nGenerated adapters repeat complete rolled-back PostgreSQL operations for SQLSTATE\n40001/40P01, with bounded context-aware backoff. SQLite retains its writer lock.\nThe generator excludes methods that access SQL outside their transaction or own\nmutable in-memory batches. Provider requests remain outside every transaction.\n\n"
	for _, file := range files {
		name := filepath.Base(file)
		original := strings.TrimSuffix(name, "_retry_generated.go") + ".go"
		text += "- `" + name + "` wraps the transactional methods in `" + original + "`.\n"
	}
	check(os.WriteFile(path, []byte(text), 0o644))
}

func check(err error) {
	if err != nil {
		panic(err)
	}
}
