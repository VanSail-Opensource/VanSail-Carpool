"""Build a reviewable PostgreSQL baseline from the final isolated SQLite fixture.

Timestamp TEXT is intentional: the deployment owner selected exact preservation.
This generator only consumes schema/empty-installation metadata, never live rows.
"""

import json
import hashlib
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TOKENS = re.compile(r"'(?:''|[^'])*'|\"(?:\"\"|[^\"])*\"|--[^\n]*|/\*.*?\*/|\w+|\s+|.", re.S)


def convert(sql):
    tokens = TOKENS.findall(sql)
    for i, token in enumerate(tokens):
        upper = token.upper()
        if upper == "INTEGER":
            tokens[i] = "BIGINT"
        elif upper == "BLOB":
            tokens[i] = "BYTEA"
        elif upper == "REAL":
            tokens[i] = "DOUBLE PRECISION"
        elif upper == "IS":
            following = [j for j in range(i + 1, len(tokens)) if not tokens[j].isspace()]
            if not following:
                raise ValueError("incomplete IS expression")
            j = following[0]
            if tokens[j].upper() == "NOT":
                if tokens[following[1]].upper() not in ("NULL", "TRUE", "FALSE"):
                    tokens[i], tokens[j] = "IS DISTINCT FROM", ""
            elif tokens[j].upper() not in ("NULL", "TRUE", "FALSE"):
                tokens[i] = "IS NOT DISTINCT FROM"
    return re.sub(r"BIGINT\s+PRIMARY KEY\s+AUTOINCREMENT", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "".join(tokens), flags=re.I)


def trigger(obj):
    match = re.fullmatch(r"CREATE TRIGGER\s+(\w+)\s+(BEFORE|AFTER)\s+(.+?)\s+ON\s+(\w+)\s*(.*?)\bBEGIN\b(.*)\bEND\s*", obj["sql"], re.S | re.I)
    if not match:
        raise ValueError("unsupported trigger: " + obj["name"])
    name, timing, event, table, when, body = match.groups()
    condition = convert(when[4:].strip()) if when.upper().startswith("WHEN") else None
    body = convert(body.strip())
    body = re.sub(r"SELECT\s+RAISE\(ABORT,('(?:''|[^'])*')\)", r"RAISE EXCEPTION USING MESSAGE=\1, ERRCODE='23514'", body, flags=re.I)
    if "RAISE(ABORT" in body.upper():
        raise ValueError("unsupported RAISE: " + name)
    if condition:
        body = "IF " + condition + " THEN\n" + body + "\nEND IF;"
    return f"""-- +goose StatementBegin
CREATE FUNCTION \"{name}_fn\"() RETURNS trigger LANGUAGE plpgsql AS $vansail$
BEGIN
{body}
IF TG_OP='DELETE' THEN RETURN OLD; END IF;
RETURN NEW;
END;
$vansail$;
-- +goose StatementEnd
CREATE TRIGGER \"{name}\" {timing} {event} ON \"{table}\" FOR EACH ROW EXECUTE FUNCTION \"{name}_fn\"();
"""


def index_sql(sql):
    # PostgreSQL requires parentheses around a CASE index expression. This is
    # trusted inventoried DDL, with one reviewed CASE expression in the baseline.
    converted = convert(sql)
    if re.search(r"\(\s*CASE\b", converted, re.I):
        converted, count = re.subn(r"\(\s*(CASE\b.*?\bEND)\s*\)", r"((\1))", converted, flags=re.S | re.I)
        if count != 1:
            raise ValueError("unreviewed CASE index grammar")
    return converted


def main():
    inventory = json.loads((ROOT / "docs/plans/postgresql/sqlite-inventory.json").read_text(encoding="utf-8"))
    tables = {o["name"]: o for o in inventory["objects"] if o["type"] == "table"}
    dependencies = {name: set(re.findall(r'REFERENCES\s+"?(\w+)', o["sql"], re.I)) - {name} for name, o in tables.items()}
    ordered = []
    while dependencies:
        ready = sorted(name for name, deps in dependencies.items() if not deps)
        if not ready:
            raise ValueError("cyclic FK graph requires explicit deferred constraint phase")
        for name in ready:
            ordered.append(name)
            del dependencies[name]
        for deps in dependencies.values():
            deps.difference_update(ready)
    chunks = ["-- +goose Up\n-- Final SQLite schema; exact timestamp text retained by deployment-owner decision.\n"]
    for name in ordered:
        chunks.append(convert(tables[name]["sql"]) + ";\n")
    chunks.append((ROOT / "docs/plans/postgresql/fixture-seeds.sql").read_text(encoding="utf-8"))
    for version in inventory["migrations"]:
        chunks.append("INSERT INTO schema_migrations(version,applied_at) VALUES('" + version.replace("'", "''") + "',vansail_now());\n")
    for obj in inventory["objects"]:
        if obj["type"] == "index":
            chunks.append(index_sql(obj["sql"]) + ";\n")
        elif obj["type"] == "trigger":
            chunks.append(trigger(obj))
    chunks.append("-- +goose Down\n-- +goose StatementBegin\nDO $$ BEGIN RAISE EXCEPTION 'Authoritative database downgrades require a separately verified recovery'; END $$;\n-- +goose StatementEnd\n")
    destination = ROOT / "internal/platform/database/postgres/migrations/00002_baseline.sql"
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text("\n".join(chunks), encoding="utf-8", newline="\n")
    contract = {
        "order": ordered,
        "tables": [{"name": t["name"], "columns": t["columns"]} for t in inventory["tables"]],
        "indexes": [o["name"] for o in inventory["objects"] if o["type"] == "index"],
        "triggers": [o["name"] for o in inventory["objects"] if o["type"] == "trigger"],
    }
    (destination.parent.parent / "contract.json").write_text(json.dumps(contract, indent=2) + "\n", encoding="utf-8", newline="\n")
    canonical = "".join(o["type"] + "\0" + o["name"] + "\0" + o["sql"].replace("\r", "") + "\0" for o in inventory["objects"])
    (destination.parent.parent / "source-schema.sha256").write_text(hashlib.sha256(canonical.encode()).hexdigest() + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
